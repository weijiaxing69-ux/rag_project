"""
全局配置。

改造目标：从「单文档 RAG 问答」升级为「多法规差异 / 冲突 / 漏洞对比分析」。
本文件集中承载改造后的可调参数，其余模块只读这里。
"""

# ============================================================
# 存储路径
# ============================================================
md5_path = "./md5.txt"

# 法条级集合。与旧的 "rag" 集合分开：旧集合里的切片是 1000 字硬切、
# 没有法规元数据，混在一起会污染「按法规过滤」的检索。
# 旧集合保留不删，随时可回退。
collection_name = "rag_law"

# 持久化目录。存储层已从 Chroma 换成自建的 numpy+json 向量库（simple_store.py），
# 绕开了 chromadb 在这台机器上无法创建数据库文件的问题。
# 每个集合存成 <collection>.vectors.npy + <collection>.records.json 两个文件。
persist_directory = "./chroma_law"

# ============================================================
# 入库：法条级切分
# ============================================================
# 以「第X条」为最小单元切分，不再按固定字数硬切。
# 单条超过 sub_split_threshold 时，才按 sub_separators 做二次切分。
sub_split_threshold = 1200
sub_split_overlap = 0
# 二次切分的优先级：先按「项」拆，再按句号拆，最后才按空白硬拆
sub_separators = ["\n（", "\n(", "。", "；", "\n", " ", ""]

# 入库结构版本。解析逻辑或元数据字段变化时必须 +1：
# 入库指纹里带上它，老记录的 md5 就不会与新算法算出的指纹相同，
# 从而避免「内容没变 → 判定已入库 → 实际元数据还是旧的」这种静默跳过。
ingest_schema_version = 2

# 单次 add_texts 提交的记录数上限。
# 实测：元数据字段较多（18 个）时，一次提交 8 条就会触发
# "Failed to apply logs to the metadata segment"，7 条可以。分批写入更稳，
# 代价只是多几次调用。这里取 6 留出余量。
ingest_batch_size = 6

# 说明：embedding 的批量提交由 langchain_community 内部处理
# （text-embedding-v3 每批 10 条，见 embeddings/dashscope.py 的 BATCH_SIZE），
# 这里不需要再包一层。

# ============================================================
# 检索
# ============================================================
retrieve_k = 8          # 通用检索召回条数（原值 2 太小，跨法规覆盖不了）
per_law_k = 4           # 对比模式下，每部法规的召回配额
max_laws = 4            # 单次对比最多参与的法规数
use_mmr = True          # 用 MMR 去冗余，避免同一部法规的相邻条文刷满召回位
mmr_lambda = 0.6        # 0=最大多样性，1=最大相关性

# 关键词兜底：法条号、专有术语这类精确匹配，纯向量召回容易漏
enable_keyword_fallback = True
keyword_k = 3

# ============================================================
# 模型
# ============================================================
embedding_model_name = "text-embedding-v3"
chat_model_name = "qwen3-max"
# 法律比对要求稳定复现，温度必须压低；原代码没有显式设置，用的是默认值。
chat_temperature = 0.1

# ============================================================
# 对比分析
# ============================================================
# 送进 prompt 的证据总量上限（字符），防止多法规长条文把上下文撑爆
max_context_chars = 24000

# 单条证据送进 prompt 时的字符上限。
# 条文太长时截断会丢细节，太松又会挤掉别的法规的配额，800 是折中值。
evidence_item_chars = 800

# 对抗幻觉的关键一步：拿结论回头核对引用是否真的存在于检索结果里
enable_self_check = True

# 调试开关：打开后会把每次送进模型的提示词打印到控制台。
# 原版是无条件打印的，在 Streamlit 里会把日志刷满，所以改成默认关闭。
debug_print_prompt = False

# 「漏洞」的可核查分类。不收敛成有限类别，模型会自由发挥编造漏洞。
LOOPHOLE_TYPES = [
    "冲突",
    "空白",
    "衔接断裂",
    "时效范围错位",
    "用语不一致",
]

# 比较维度：先由模型针对具体问题生成，这里只是兜底默认集
DEFAULT_DIMENSIONS = [
    "适用对象与范围",
    "行为规范要求",
    "审批与程序",
    "法律责任与处罚",
    "生效时间与效力层级",
]

# ============================================================
# 会话
# ============================================================
# 原代码把 session_id 写死成 user_001，导致所有人共用一份历史，
# 且上一轮的结论会被当成事实喂进下一轮。这里只保留默认值，
# 实际会话 id 由界面生成、按「分析任务」隔离。
default_session_id = "default"

# 兼容旧调用点
session_config = {
    "configurable": {
        "session_id": default_session_id
    }
}


def is_enabled(value) -> bool:
    """把 '关闭' / '否' / False 之类的界面取值统一判成布尔。"""
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() not in {"", "0", "false", "no", "off", "否", "关闭"}
